// Writes the keyword rules of src/egglog.grammar, between its "generated" markers, and
// src/keywords.ts for completion, from spec/keywords.json.
import {readFileSync, writeFileSync} from "node:fs"

const root = new URL("../", import.meta.url)
const file = path => new URL(path, root)
const src = "packages/codemirror-lang-egglog/src/"
const keywords = JSON.parse(readFileSync(file("spec/keywords.json"), "utf8"))
const {commands, actions, schedules} = keywords

// The grammar tells only commands and schedules apart by position (see TopList).
const clash = actions.filter(a => commands.includes(a) || schedules.includes(a))
if (clash.length) throw new Error(`action keywords that are also commands or schedules: ${clash.join(" ")}`)

const rule = (name, words, first = []) =>
  `${name} {\n  ${[...first, ...words.map(w => `@specialize<word, ${JSON.stringify(w)}>`)].join(" |\n  ")}\n}\n`
const all = [...new Set([...commands, ...actions, ...schedules])].sort()

const begin = "// generated by gen/grammar.mjs from spec/keywords.json\n"
const end = "// end generated\n"
const block = [
  rule("TopCommandKeyword[@name=CommandKeyword]", commands),
  rule("NestedCommandKeyword[@name=CommandKeyword]", commands.filter(c => !schedules.includes(c))),
  rule("ActionKeyword", actions),
  rule("ScheduleKeyword", schedules),
  // At top level a schedule keyword is an ordinary function name.
  rule("TopCallee[@name=Callee]", schedules.filter(s => !commands.includes(s)), ["word"]),
  rule("keyword", all),
].join("\n")

const grammarPath = file(src + "egglog.grammar")
const grammar = readFileSync(grammarPath, "utf8")
const from = grammar.indexOf(begin)
const to = grammar.indexOf(end)
if (from < 0 || to < from) throw new Error("src/egglog.grammar lacks the generated markers")
writeFileSync(grammarPath, grammar.slice(0, from + begin.length) + block + grammar.slice(to))

const list = words => JSON.stringify(words)
writeFileSync(
  file(src + "keywords.ts"),
  "// Generated by gen/grammar.mjs from spec/keywords.json. Do not edit.\n\n" +
    `export const commands = ${list(commands)}\n` +
    `export const actions = ${list(actions)}\n` +
    `export const schedules = ${list(schedules)}\n` +
    `export const options = ${list(keywords.options)}\n`,
)
